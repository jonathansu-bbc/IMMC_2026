image_path = "UKNP.png" # Change to INP.png or UKNP.png

def analyze_point(x, y, m):
    # Load image and convert BGR (OpenCV default) to RGB
    img_bgr = cv2.imread(image_path)
    if img_bgr is None:
        return "Image not found."
    
    img_rgb = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)

    dist = []

    # Features to measure distance to

    for i in range(len(m)):
        mask = np.all(img_rgb == m[i], axis=-1)

        if not np.any(mask):
            dist.append(400)
            continue

        binary_mask = np.where(mask, 0, 1).astype(np.uint8)
        dist_map = cv2.distanceTransform(binary_mask, cv2.DIST_L2, 5)

        dist.append(round(float(dist_map[y, x])))

    return dist


def get_average_results(coords, map):
    # 1. Collect all lists into a single Python list
    all_results = []
    
    for x, y in coords:
        result = analyze_point(x, y, map)
        all_results.append(result)
    
    # 2. Convert to a NumPy array
    # This creates a shape of (number_of_coords, 8)
    results_array = np.array(all_results)
    
    # 3. Calculate the mean along axis 0 (the rows)
    # This results in a single list of 8 averages
    average_list = np.mean(results_array, axis=0)
    
    return average_list.tolist()

